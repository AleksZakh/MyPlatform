import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
const url = process.env.CHAT_TEST_DATABASE_URL;
if (!url || !new URL(url).pathname.endsWith('_chat_test')) throw new Error('Use a fresh disposable *_chat_test database');
process.env.DATABASE_URL = url;
const { prisma } = await import('../../server/utils/prisma');
const { createGroup, changeGroup, getGroup } = await import('../../server/services/chat/groups');
const { saveMessage, membership, markRead, openDialog } = await import('../../server/services/chat/repository');
const { groupCreateInput, groupChangeInput } = await import('../../server/services/chat/group-input');
const failure = (code: number) => (e: any) => e.statusCode === code;
test('group roles, full history, unread baseline, removal, archive, retry and direct chats', async () => {
 try {
  const base = await readFile(process.env.BASE_SCHEMA_SQL!, 'utf8');
  for (const sql of base.split(';').filter(s => s.trim())) await prisma.$executeRawUnsafe(sql);
  const migration = await readFile(new URL('../../prisma/migrations/20261012150000_chat_groups/migration.sql', import.meta.url),'utf8');
  for (const sql of migration.split(';').filter(s=>s.trim())) await prisma.$executeRawUnsafe(sql);
  for (let id=1;id<=7;id++) await prisma.user.create({data:{id,authType:'DOMAIN',login:`user-${id}`,status:id===5?'BLOCKED':'ACTIVE'}});
  const request = randomUUID();
  const group = await createGroup(1, 'Рабочая группа', [2,3], request);
  assert.equal((await createGroup(1,'Рабочая группа',[2,3],request)).id,group.id);
  assert.equal(await prisma.chatConversation.count(),1);
  await assert.rejects(createGroup(5,'Forbidden',[1],randomUUID()),failure(403));
  await assert.rejects(createGroup(1,'Disabled',[5],randomUUID()),failure(409));
  await assert.rejects(getGroup(4,group.id),failure(404));
  await assert.rejects(changeGroup(3,group.id,{action:'rename',name:'Intrusion'}),failure(403));
  await changeGroup(1,group.id,{action:'role',userId:2,role:'ADMIN'});
  await changeGroup(2,group.id,{action:'rename',name:'Переименована'});
  assert.equal((await getGroup(3,group.id)).name,'Переименована');
  await assert.rejects(changeGroup(2,group.id,{action:'role',userId:3,role:'ADMIN'}),failure(403));
  await assert.rejects(changeGroup(2,group.id,{action:'remove',userId:1}),failure(409));
  const first = await saveMessage(1,group.id,'История до вступления',randomUUID());
  await changeGroup(2,group.id,{action:'add',userIds:[4]});
  const joined = await membership(4,group.id);
  assert.equal(joined.unreadFrom, first.id); assert.equal(joined.readThrough,0);
  const history = await prisma.chatMessage.findMany({where:{conversationId:group.id,conversation:{members:{some:{userId:4}}}}});
  assert.equal(history[0]?.body,'История до вступления');
  const clientId = randomUUID();
  const next = await saveMessage(4,group.id,'Новое сообщение',clientId);
  assert.equal((await saveMessage(4,group.id,'Новое сообщение',clientId)).id,next.id);
  await markRead(4,group.id,next.id);
  await changeGroup(2,group.id,{action:'remove',userId:4});
  await assert.rejects(membership(4,group.id),failure(404));
  await assert.rejects(saveMessage(4,group.id,'Новое сообщение',clientId),failure(404));
  assert.equal(await prisma.chatMessage.count({where:{conversationId:group.id}}),2);
  await changeGroup(1,group.id,{action:'add',userIds:[4]});
  assert.equal(await prisma.chatMessage.count({where:{conversationId:group.id,conversation:{members:{some:{userId:4}}}}}),2);
  await changeGroup(1,group.id,{action:'role',userId:3,role:'ADMIN'});
  await assert.rejects(changeGroup(2,group.id,{action:'remove',userId:3}),failure(403));
  await assert.rejects(changeGroup(1,group.id,{action:'leave'}),failure(409));
  await changeGroup(1,group.id,{action:'transfer',userId:2});
  assert.equal((await getGroup(2,group.id)).myRole,'OWNER');
  await assert.rejects(changeGroup(1,group.id,{action:'archive',archived:true}),failure(403));
  await changeGroup(2,group.id,{action:'archive',archived:true});
  await assert.rejects(saveMessage(1,group.id,'Archived',randomUUID()),failure(409));
  assert.equal((await getGroup(1,group.id)).archived,true);
  await changeGroup(2,group.id,{action:'archive',archived:false});
  await changeGroup(1,group.id,{action:'leave'});
  await assert.rejects(getGroup(1,group.id),failure(404));
  // One disabled member does not block all other group participants.
  await prisma.user.update({where:{id:3},data:{status:'DISABLED'}});
  await saveMessage(2,group.id,'Продолжаем работу',randomUUID());
  await assert.rejects(saveMessage(3,group.id,'Disabled',randomUUID()),failure(403));
  const direct=await openDialog(6,7);
  await saveMessage(6,direct.id,'Личное сообщение',randomUUID());
  await prisma.user.update({where:{id:7},data:{status:'BLOCKED'}});
  await assert.rejects(saveMessage(6,direct.id,'Blocked',randomUUID()),failure(403));
  await assert.rejects(changeGroup(6,direct.id,{action:'add',userIds:[2]}),failure(404));
  assert.equal(groupCreateInput.safeParse({clientId:request,name:' ',userIds:[2]}).success,false);
  assert.equal(groupChangeInput.safeParse({action:'role',userId:2,role:'OWNER'}).success,false);
  assert.equal(await prisma.chatMember.count({where:{conversationId:group.id,role:'OWNER'}}),1);
 } finally {await prisma.$disconnect();}
});
